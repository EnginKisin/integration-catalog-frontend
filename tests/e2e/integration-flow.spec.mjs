test('ortam değiştirirken girilen erişim bilgisini korur; yalnızca eksik sistem bağlantısını ekler', async ({ page }) => {
  const state = await mockCatalog(page, { item: { hasMiddleware: true, middlewareSystemId: 3 } })
  await page.goto('/')
  await page.getByRole('button', { name: 'Sipariş aktarımı ayrıntılarını aç', exact: true }).click()
  await page.getByRole('button', { name: '+ DEV ekle', exact: true }).click()

  const destination = page.getByRole('group', { name: 'DEV / CRM', exact: true })
  await destination.getByRole('textbox', { name: 'URL (en fazla 100 karakter)', exact: true }).fill('https://test.crm.example.test')
  await destination.getByRole('combobox', { name: 'Kimlik doğrulama', exact: true }).selectOption('API_KEY')
  await destination.getByLabel('API anahtarı', { exact: true }).fill('environment-test-key')
  await destination.getByRole('combobox', { name: 'Ortam', exact: true }).selectOption('TEST')

  const moved = page.getByRole('group', { name: 'TEST / CRM', exact: true })
  await expect(moved.getByLabel('API anahtarı', { exact: true })).toHaveValue('environment-test-key')
  await expect(moved.getByRole('textbox', { name: 'URL (en fazla 100 karakter)', exact: true })).toHaveValue('https://test.crm.example.test')
  await page.getByRole('button', { name: '+ TEST ekle', exact: true }).click()
  const middleware = page.getByRole('group', { name: 'TEST / ESB', exact: true })
  await middleware.getByRole('textbox', { name: 'URL (en fazla 100 karakter)', exact: true }).fill('https://test.esb.example.test')
  await page.getByRole('group', { name: 'DEV / ESB', exact: true }).getByRole('button', { name: 'Satırı kaldır', exact: true }).click()
  await expect(page.getByRole('button', { name: '✓ TEST eklendi', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '+ DEV ekle', exact: true })).toBeEnabled()

  await exit(page).click()
  await expect(page.getByRole('heading', { name: 'Entegrasyonlar', exact: true })).toBeVisible()
  const saved = writes(state, '/integrations/30/configs')[0].body
  expect(saved).toHaveLength(2)
  expect(saved).toEqual(expect.arrayContaining([
    expect.objectContaining({ environmentType: 'TEST', configTarget: 'DESTINATION', url: 'https://test.crm.example.test', authCredentials: { apiKey: 'environment-test-key' } }),
    expect.objectContaining({ environmentType: 'TEST', configTarget: 'MIDDLEWARE', url: 'https://test.esb.example.test' }),
  ]))
})
