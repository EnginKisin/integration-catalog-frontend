test('senkron içeriklerin hepsini doğrular; eksik yanıtta sonraki adıma geçmez', async ({ page }) => {
  const state = await mockCatalog(page, { item: { isSync: true }, configs: [config()] })
  await page.goto('/')
  await page.getByRole('button', { name: 'Sipariş aktarımı ayrıntılarını aç', exact: true }).click()
  const editors = page.getByRole('textbox', { name: 'JSON içeriği', exact: true })
  await editors.nth(0).fill('{"orderId":123}')
  await editors.nth(1).fill('{broken')
  await next(page).click()
  await expect(page.getByRole('alert').filter({ hasText: 'geçerli bir JSON' }).first()).toBeVisible()
  expect(writes(state, '/integrations/30/mappings/schemas')).toHaveLength(0)
  await expect(editors.nth(0)).toHaveValue('{"orderId":123}')
  await editors.nth(1).fill('{}')
  await next(page).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Devam etmek için bu eksikleri tamamlayın' })).toBeVisible()
  await expect(current(page)).toContainText('İstek ve yanıt')
  await editors.nth(1).fill('{"result":"ok"}')
  await next(page).click()
  await expect(current(page)).toContainText('Özet ve tamamlama')
  await expect(steps(page).getByRole('button')).toHaveCount(4)
  await expect(steps(page).getByRole('button', { name: /Alan eşleme/ })).toHaveCount(0)
  expect(writes(state, '/integrations/30/mappings/fields')).toHaveLength(0)
})

