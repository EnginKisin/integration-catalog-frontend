test('kayıtlı erişim bilgisini okumadan korur; özel JSON alanlarını silmez', async ({ page }) => {
  const state = await mockCatalog(page, { item: {}, configs: [config({ authType: 'API_KEY', credentialsConfigured: true })] })
  await page.goto('/')
  await page.getByRole('button', { name: 'Sipariş aktarımı ayrıntılarını aç', exact: true }).click()
  await steps(page).getByRole('button', { name: /Ortam ayarları/ }).click()
  await expect(page.getByLabel('API anahtarı', { exact: true })).toBeEmpty()
  await page.getByLabel('URL (en fazla 100 karakter)', { exact: true }).fill('https://changed.example.test')
  await next(page).click()
  await expect(current(page)).toContainText('İstek ve yanıt')
  await expect(page.getByText('Ortam ayarları kaydedildi.', { exact: true })).toBeVisible()
  expect(writes(state, '/integrations/30/configs')[0].body[0]).not.toHaveProperty('authCredentials')
  expect(state.calls.some((call) => call.path.endsWith('/credentials'))).toBe(false)
  await steps(page).getByRole('button', { name: /Ortam ayarları/ }).click()
  await page.getByRole('button', { name: 'Gelişmiş: özel alanlar (JSON)', exact: true }).click()
  const json = page.getByRole('textbox', { name: 'Erişim bilgileri (JSON nesnesi)', exact: true })
  await json.fill('{"apiKey":"test-only","headerName":"X-Custom-Key"}')
  await page.getByRole('button', { name: 'Form alanlarına dön', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'özel alanlar' })).toBeVisible()
  await expect(json).toHaveValue('{"apiKey":"test-only","headerName":"X-Custom-Key"}')
  await exit(page).click()
  await expect(page.getByRole('heading', { name: 'Entegrasyonlar', exact: true })).toBeVisible()
  expect(writes(state, '/integrations/30/configs')[1].body[0].authCredentials).toEqual({ apiKey: 'test-only', headerName: 'X-Custom-Key' })
})

