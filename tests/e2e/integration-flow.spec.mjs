import { test, expect } from '@playwright/test'
import { mockCatalog } from './mock-api.mjs'

const next = (page) => page.getByRole('button', { name: 'Kaydet ve devam et →', exact: true })
const exit = (page) => page.getByRole('button', { name: 'Kaydet ve çık', exact: true })
const steps = (page) => page.getByRole('navigation', { name: 'Entegrasyon adımları' })
const current = (page) => steps(page).locator('[aria-current="step"]')
const writes = (state, path) => state.calls.filter((call) => call.method !== 'GET' && call.path === path)
const config = (changes = {}) => ({ id: 1, environmentType: 'DEV', configTarget: 'DESTINATION', url: 'https://example.test', authType: 'NONE', credentialsConfigured: false, ...changes })

async function start(page, name = 'Sipariş aktarımı') {
  await page.goto('/')
  await page.getByRole('main').getByRole('button', { name: 'Yeni entegrasyon', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Kaydet', exact: true })).toHaveCount(0)
  await page.getByLabel('Servis adı', { exact: true }).fill(name)
  await page.getByRole('combobox', { name: 'Kaynak sistem', exact: true }).selectOption('1')
  await page.getByRole('combobox', { name: 'Hedef sistem', exact: true }).selectOption('2')
}

test('taslaktan tamamlamaya ilerler; değişmeyen adımı kaydetmek tamamlandı durumunu bozmaz', async ({ page }, testInfo) => {
  const state = await mockCatalog(page)
  await start(page)
  await page.screenshot({ path: testInfo.outputPath('desktop-basics.png'), fullPage: true })
  await next(page).click()
  await expect(current(page)).toContainText('Ortam ayarları')
  await expect(page.getByText('Taslak oluşturuldu.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: '+ DEV ekle', exact: true }).click()
  await page.getByLabel('URL (en fazla 100 karakter)', { exact: true }).fill('https://dev.example.test/orders')
  await page.getByRole('combobox', { name: 'Kimlik doğrulama', exact: true }).selectOption('API_KEY')
  await page.getByLabel('API anahtarı', { exact: true }).fill('e2e-only-key')
  await page.screenshot({ path: testInfo.outputPath('desktop-environment.png'), fullPage: true })
  await next(page).click()
  await expect(current(page)).toContainText('İstek ve yanıt')
  expect(writes(state, '/integrations/30/configs')[0].body[0].authCredentials).toEqual({ apiKey: 'e2e-only-key' })
  await page.getByRole('textbox', { name: 'JSON içeriği', exact: true }).first().fill('{"orderId":"123"}')
  await next(page).click()
  await expect(current(page)).toContainText('Özet ve tamamlama')
  await expect(steps(page).getByRole('button')).toHaveCount(4)
  await expect(steps(page).getByRole('button', { name: /Alan eşleme/ })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Mevcut alan eşlemeleri', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '← Önceki adım', exact: true }).click()
  await expect(current(page)).toContainText('İstek ve yanıt')
  await next(page).click()
  await expect(current(page)).toContainText('Özet ve tamamlama')
  await expect(page.getByRole('main').getByRole('button').last()).toHaveText('Kaydı kapat')
  await page.screenshot({ path: testInfo.outputPath('desktop-review.png'), fullPage: true })
  await expect(page.getByRole('button', { name: 'Katalog kaydını tamamla', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Katalog kaydını tamamla', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Katalog kaydı tamamlandı', exact: true })).toBeDisabled()
  await steps(page).getByRole('button', { name: /Temel bilgiler/ }).click()
  await exit(page).click()
  await expect(page.getByRole('heading', { name: 'Entegrasyonlar', exact: true })).toBeVisible()
  expect(state.record.status).toBe('COMPLETED')
  expect(writes(state, '/integrations/30')).toHaveLength(0)
  expect(writes(state, '/integrations/30/complete')).toHaveLength(1)
  expect(writes(state, '/integrations/30/mappings/fields')).toHaveLength(0)
})

